// Copies the published OpenAPI contract from the backend repository into contract/ and records its
// provenance in contract/SOURCE.md. Source path: CONTRACT_SOURCE (default ../docs-system-backend/api/openapi.yaml).
// Refuses to copy a contract that is not published (backend not on `develop` or file with uncommitted changes).
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { parse } from 'yaml';

const PUBLISHED_BRANCH = 'develop';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(
  root,
  process.env.CONTRACT_SOURCE ?? '../docs-system-backend/api/openapi.yaml',
);
const target = resolve(root, 'contract/openapi.yaml');

function fail(message) {
  console.error(`contract:sync — ${message}`);
  process.exit(1);
}

if (!existsSync(source)) fail(`source not found: ${source}`);

const sourceDir = dirname(source);
const git = (...args) =>
  execFileSync('git', ['-C', sourceDir, ...args], { encoding: 'utf8' }).trim();

let repoRoot;
let branch;
let commit;
let dirty;
try {
  repoRoot = git('rev-parse', '--show-toplevel');
  branch = git('rev-parse', '--abbrev-ref', 'HEAD');
  commit = git('rev-parse', 'HEAD');
  dirty = git('status', '--porcelain', '--', basename(source));
} catch {
  fail(`${sourceDir} is not inside a readable git repository`);
}

if (branch !== PUBLISHED_BRANCH) {
  fail(`backend is on "${branch}", not "${PUBLISHED_BRANCH}"; not copying an unpublished contract`);
}
if (dirty) {
  fail(
    `${basename(source)} has uncommitted changes in the backend; commit them first, not copying`,
  );
}

const version = parse(readFileSync(source, 'utf8'))?.info?.version;
if (!version) fail('info.version not found in the contract');

mkdirSync(dirname(target), { recursive: true });
copyFileSync(source, target);
writeFileSync(
  resolve(root, 'contract/SOURCE.md'),
  [
    '# Contract source',
    '',
    'Generated by `npm run contract:sync`. Do not edit by hand.',
    '',
    `- Contract version (info.version): ${version}`,
    `- Backend repository: ${basename(repoRoot)}`,
    `- Backend branch: ${branch}`,
    `- Backend commit: ${commit}`,
    '',
  ].join('\n'),
);
console.log(`contract:sync — copied OpenAPI ${version} (${branch}@${commit.slice(0, 7)})`);
